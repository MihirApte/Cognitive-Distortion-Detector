"""
src/safety.py
-------------
Crisis detection and safety guardrails for the Cognitive Distortion Detector.

Design decision (interview defence):
    Crisis text is routed to a fixed, pre-written safe message - NOT to an LLM.
    LLMs can engage unpredictably with distressed users, generate inappropriate
    suggestions, or subtly validate harmful thinking. A hard-coded response is
    the only safe choice in a mental-health-adjacent tool.

Usage:
    from src.safety import check_crisis, SAFE_RESPONSE, DISCLAIMER

    result = check_crisis(user_text)
    if result["is_crisis"]:
        return SAFE_RESPONSE
"""

from __future__ import annotations
import re

# ── Disclaimer (always shown in UI) ──────────────────────────────────────────
DISCLAIMER = (
    "This tool is for educational purposes only and does not constitute "
    "medical or psychological advice. If you are in distress, please contact "
    "a mental health professional."
)

# ── Fixed safe response for crisis inputs ─────────────────────────────────────
# Never generated by an LLM - always this exact text.
SAFE_RESPONSE = {
    "is_crisis": True,
    "message": (
        "It sounds like you may be going through something serious. "
        "This tool is not designed to help in crisis situations. "
        "Please reach out to someone who can support you:\n\n"
        "- iCall (India): 9152987821\n"
        "- Vandrevala Foundation: 1860-2662-345 (24/7, India)\n"
        "- Crisis Text Line (US): Text HOME to 741741\n"
        "- International Association for Suicide Prevention: "
        "https://www.iasp.info/resources/Crisis_Centres/"
    ),
}

# ── Crisis keyword patterns ────────────────────────────────────────────────────
# Covers direct statements, indirect hints, and common phrasings.
# Deliberately broad - false positives (routing a non-crisis to safe message)
# are far preferable to false negatives here.
_CRISIS_PATTERNS: list[str] = [
    # direct suicide / self-harm
    r"\bkill\s+my\s*self\b",
    r"\bsuicid",
    r"\bend\s+my\s+life\b",
    r"\btake\s+my\s+(own\s+)?life\b",
    r"\bwant\s+to\s+die\b",
    r"\bwish\s+i\s+(was|were)\s+dead\b",
    r"\bbetter\s+off\s+dead\b",
    r"\bnot\s+worth\s+living\b",
    r"\blife\s+is\s+not\s+worth\b",
    r"\bself[\s-]?harm\b",
    r"\bhurt\s+(my|them|him|her)\s*self\b",
    r"\bcut(ting)?\s+(my|them|him|her)\s*self\b",
    r"\boverdos",
    r"\bhanging\s+(my|them|him|her)\s*self\b",
    r"\bjump\s+off\b",
    r"\bend\s+(their|his|her|my|our|your)\s+life\b",
    # indirect / passive ideation
    r"\bno\s+reason\s+to\s+(be\s+)?alive\b",
    r"\bcan'?t\s+go\s+on\b",
    r"\bcan'?t\s+do\s+this\s+anymore\b",
    r"\bdon'?t\s+want\s+to\s+be\s+here\b",
    r"\beveryone\s+would\s+be\s+better\s+without\s+me\b",
    r"\bwish\s+i\s+(could\s+)?disappear\b",
]

_COMPILED = [re.compile(p, re.IGNORECASE) for p in _CRISIS_PATTERNS]


def check_crisis(text: str) -> dict:
    """
    Scan text for crisis signals.

    Returns
    -------
    dict with keys:
        is_crisis  : bool
        matched_pattern : str | None  (for logging, never shown to user)
    """
    text = text.strip()
    for pattern in _COMPILED:
        m = pattern.search(text)
        if m:
            return {
                "is_crisis": True,
                "matched_pattern": pattern.pattern,
            }
    return {
        "is_crisis": False,
        "matched_pattern": None,
    }


# ── Jailbreak / misuse detection ─────────────────────────────────────────────
# Catches attempts to repurpose the tool as a therapy or advice generator.
_MISUSE_PATTERNS: list[str] = [
    r"ignore\s+(previous|all|your)\s+instructions",
    r"pretend\s+(you\s+are|you're|to\s+be)\s+a\s+(therapist|doctor|psychologist)",
    r"act\s+as\s+a\s+(therapist|doctor|psychologist|counsellor)",
    r"give\s+me\s+(medical|therapy|clinical)\s+advice",
    r"diagnos",
    r"prescri",
]

_MISUSE_COMPILED = [re.compile(p, re.IGNORECASE) for p in _MISUSE_PATTERNS]

MISUSE_RESPONSE = {
    "is_misuse": True,
    "message": (
        "This tool detects cognitive distortion patterns in text for "
        "educational purposes only. It cannot give therapy, medical advice, "
        "or diagnoses. Please speak with a licensed mental health professional "
        "for personal support."
    ),
}


def check_misuse(text: str) -> dict:
    """Detect attempts to use the tool as a therapy or advice generator."""
    for pattern in _MISUSE_COMPILED:
        if pattern.search(text):
            return {"is_misuse": True, "matched_pattern": pattern.pattern}
    return {"is_misuse": False, "matched_pattern": None}
